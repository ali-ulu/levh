def _resolved_db_path() -> str:
    """Absolute path to the database."""
    return os.path.abspath(os.getenv("SQLITE_DB_PATH", "./stackmemory.db"))


def _levh_url() -> str:
    """LEVH server URL."""
    return os.getenv("LEVH_URL", "http://localhost:8000")


