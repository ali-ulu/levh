def install_claude_code_hook(limit: int = 5, with_checkpoint: bool = False) -> dict:
    """Install the SessionStart hook for Claude Code."""
    from .hooks import _install_session_hook
    result = _install_session_hook(limit)
    return {"ok": result == 0, "agent": "claude-code"}


def install_cursor_hook(limit: int = 5) -> dict:
    """Install auto-connect for Cursor IDE."""
    config_path = Path(".cursor/mcp.json")
    config_path.parent.mkdir(parents=True, exist_ok=True)

    entry = {
        "command": "levh",
        "args": ["mcp", "stdio"],
        "cwd": os.getcwd(),
        "env": {
            "LEVH_MCP_PROFILE": "work",
            "SQLITE_DB_PATH": _resolved_db_path(),
        },
    }

    if config_path.exists():
        try:
            config = json.loads(config_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            config = {}
    else:
        config = {}

    servers = config.setdefault("mcpServers", {})
    servers["levh"] = entry
    config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")

    # Also create .cursorrules with continuity brief
    rules_path = Path(".cursorrules")
    _write_cursorrules(rules_path)

    return {"ok": True, "agent": "cursor", "config_path": str(config_path)}


