# The auto-connect script that runs when an agent starts.
# It creates a session, loads the brief, and prints it.
_AUTO_CONNECT_TEMPLATE = '''#!/bin/sh
{marker}
# LEVH Universal Auto-Connect Hook
# Automatically connects to LEVH, creates a session, and loads the brief.
# Works for any MCP client — installed by `levh hook install --client {client}`.

LEVH_URL="${{LEVH_URL:-http://localhost:8000}}"
SQLITE_DB_PATH="${{SQLITE_DB_PATH:-{db_path}}}"
export SQLITE_DB_PATH

# 1. Create a session for this agent
SESSION_RESPONSE=$("{python}" -P -c "
import urllib.request, json, sys
try:
    req = urllib.request.Request(
        f'{levh_url}/api/sessions',
        data=json.dumps({{'name': '{agent_display} Session', 'metadata': json.dumps({{'agent': '{client}', 'auto': True}})}}).encode(),
        headers={{'Content-Type': 'application/json'}},
        method='POST'
    )
    resp = urllib.request.urlopen(req, timeout=5)
    data = json.loads(resp.read())
    print(data.get('id', ''))
except Exception:
    pass
" 2>/dev/null) || true

# 2. Get the continuity brief
BRIEF=$("{python}" -P -m server.cli continue --limit {limit} --if-any 2>/dev/null) || exit 0

# 3. Print the brief (agent will see it)
[ -n "$BRIEF" ] || exit 0
printf '%s\\n' "$BRIEF"
exit 0
'''

